require("./register-local-ts.cjs");
const assert = require("node:assert/strict");
const { packageDisplayRows } = require("../lib/teklifPackage.ts");
const row = (name, price, extra = {}) => ({ HizmetAdi: name, Adet: 2, Fiyat: price, ParaBirimi: "TRY", Iskonto: 0, Metot: "ISO", Akreditasyon: "Var", ...extra });
const net = rows => rows.reduce((sum, r) => sum + (Number(r.Adet) || 1) * (Number(r.Fiyat) || 0) * (1 - (Number(r.Iskonto) || 0) / 100), 0);
const members = [row("A", 100, { PaketGrup: "group1", PaketAdi: "Paket", Iskonto: 10 }), row("B", 200, { PaketGrup: "group1", PaketAdi: "Paket" })];
const snapshot = JSON.stringify(members);
const grouped = packageDisplayRows(members);
assert.equal(grouped.length, 1);
assert.equal(grouped[0].HizmetAdi, "Paket");
assert.equal(grouped[0].Adet, 2);
assert.equal(grouped[0].Fiyat, 290);
assert.equal(grouped[0].Iskonto, 0);
assert.deepEqual(grouped[0].UygulananParametreler, ["* A / ISO", "* B / ISO"]);
assert.equal(net(grouped), net(members));
assert.equal(JSON.stringify(members), snapshot);
const separate = [row("A", 100), row("B", 200)];
assert.deepEqual(packageDisplayRows(separate), separate);
assert.equal(packageDisplayRows([...members, row("C", 50), row("D", 25, { PaketGrup: "group2", PaketAdi: "Paket" })]).length, 3);
const mixed = [members[0], { ...members[1], Adet: 3 }];
assert.equal(net(packageDisplayRows(mixed)), net(mixed));
assert.equal(packageDisplayRows(mixed)[0].Adet, 1);
assert.match(packageDisplayRows(mixed)[0].UygulananParametreler[1], /3 adet/);
assert.equal(packageDisplayRows([members[0], { ...members[1], ParaBirimi: "EUR" }]).length, 2);
assert.equal(packageDisplayRows([]).length, 0);
console.log("PASS: separate/grouped packages, price/discount/quantity totals, parameter methods and accreditation, repeated packages, mixed currencies, unchanged underlying rows.");
