#!/usr/bin/env node
// MSSQL T-SQL dump → MySQL 8 (InnoDB, utf8mb4) converter.
// Stream-based, ~250 MB tek dosyada sorunsuz.
//
// Kullanım:
//   node scripts/mssql-to-mysql-convert.mjs <input.sql> [output-dir]
//
// Çıktı:
//   <out>/01-schema.sql   — CREATE TABLE IF NOT EXISTS + indexes + FK'ler
//   <out>/02-data.sql     — INSERT IGNORE INTO ...
//   <out>/skipped.log     — dönüşemeyen statement'lar (TRIGGER, PROCEDURE, vb.)
//
// Önemli kararlar:
//   • CREATE TABLE → CREATE TABLE IF NOT EXISTS  (mevcut 27 tablo silinmez)
//   • INSERT       → INSERT IGNORE INTO          (PK çakışmaları sessizce geçer)
//   • Tüm string kolonlar utf8mb4 / utf8mb4_unicode_ci
//   • IDENTITY → AUTO_INCREMENT (PK ile birlikte olmalı, MSSQL output zaten öyle veriyor)
//   • dbo.X → X (schema prefix kaldırılır, MySQL'de schema=database)

import { createReadStream, createWriteStream, mkdirSync, existsSync } from "node:fs";
import { createInterface } from "node:readline";
import path from "node:path";

const [, , inputArg, outDirArg] = process.argv;
if (!inputArg) {
  console.error("Kullanım: node scripts/mssql-to-mysql-convert.mjs <input.sql> [output-dir]");
  process.exit(1);
}
const inputPath = path.resolve(inputArg);
const outDir = path.resolve(outDirArg || path.join(path.dirname(inputPath), "mysql-out"));
if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });

const schemaPath = path.join(outDir, "01-schema.sql");
const dataPath = path.join(outDir, "02-data.sql");
const skippedPath = path.join(outDir, "skipped.log");

const schemaOut = createWriteStream(schemaPath, { encoding: "utf8" });
const dataOut = createWriteStream(dataPath, { encoding: "utf8" });
const skippedOut = createWriteStream(skippedPath, { encoding: "utf8" });

// MySQL ortam başlığı (utf8mb4, FK kontrol kapalı — döngüsel FK'ler için).
const header = `-- Generated by mssql-to-mysql-convert.mjs
SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;
SET UNIQUE_CHECKS = 0;
SET sql_mode = '';
`;
const footer = `\nSET FOREIGN_KEY_CHECKS = 1;\nSET UNIQUE_CHECKS = 1;\n`;
schemaOut.write(header);
dataOut.write(header);

// ── Statement buffer (GO veya ; ile ayrılır) ────────────────────────────────
let buffer = [];
let stats = { tables: 0, indexes: 0, fks: 0, inserts: 0, skipped: 0 };

function flushStatement() {
  if (!buffer.length) return;
  const raw = buffer.join("\n").trim();
  buffer = [];
  if (!raw) return;

  // Yok sayılacak SET/USE komutları
  if (/^(SET\s+(ANSI_NULLS|QUOTED_IDENTIFIER|ANSI_PADDING|NOCOUNT|IDENTITY_INSERT|XACT_ABORT|CONCAT_NULL_YIELDS_NULL|ARITHABORT|NUMERIC_ROUNDABORT|ANSI_WARNINGS)\b|USE\s+\[)/i.test(raw)) {
    return;
  }
  // Yorumlar tek başına gelirse her iki çıktıya da yaz
  if (/^\s*(--|\/\*)/.test(raw) && !/CREATE|INSERT|ALTER/i.test(raw)) {
    schemaOut.write(raw + "\n");
    return;
  }

  // Statement tipini ayırt et
  const upper = raw.toUpperCase();
  let converted, target;

  if (/^CREATE\s+TABLE\b/i.test(upper)) {
    converted = convertCreateTable(raw);
    target = schemaOut;
    stats.tables++;
  } else if (/^CREATE\s+(UNIQUE\s+)?(CLUSTERED\s+|NONCLUSTERED\s+)?INDEX\b/i.test(upper)) {
    converted = convertCreateIndex(raw);
    target = schemaOut;
    stats.indexes++;
  } else if (/^ALTER\s+TABLE\b/i.test(upper)) {
    converted = convertAlterTable(raw);
    target = schemaOut;
    if (/FOREIGN\s+KEY/i.test(upper)) stats.fks++;
  } else if (/^INSERT\b/i.test(upper)) {
    converted = convertInsert(raw);
    target = dataOut;
    stats.inserts++;
  } else if (/^(CREATE\s+(TRIGGER|PROCEDURE|FUNCTION|VIEW)|EXEC\b)/i.test(upper)) {
    skippedOut.write(`-- SKIPPED (MSSQL T-SQL):\n${raw}\nGO\n\n`);
    stats.skipped++;
    return;
  } else if (/^SET\s+IDENTITY_INSERT/i.test(upper)) {
    return; // MySQL'de gereksiz
  } else {
    // Bilinmeyen — ham haliyle skipped'a koy, ileride incelemek için
    skippedOut.write(`-- UNRECOGNIZED:\n${raw}\nGO\n\n`);
    stats.skipped++;
    return;
  }

  if (converted) target.write(converted + ";\n\n");
}

// ── Temel transformasyonlar ─────────────────────────────────────────────────
function transformIdentifiers(sql) {
  // [dbo].[X] → `X`
  sql = sql.replace(/\[dbo\]\.\[([^\]]+)\]/gi, "`$1`");
  // [schema].[X] → `X` (genel)
  sql = sql.replace(/\[(?:[A-Za-z_][\w]*)\]\.\[([^\]]+)\]/g, "`$1`");
  // [X] → `X`
  sql = sql.replace(/\[([^\]]+)\]/g, "`$1`");
  // dbo.X (bracket'sız) → X
  sql = sql.replace(/\bdbo\.(`?[A-Za-z_][\w]*`?)/gi, "$1");
  return sql;
}

function transformTypes(sql) {
  // NVARCHAR(MAX) → LONGTEXT
  sql = sql.replace(/\bNVARCHAR\s*\(\s*MAX\s*\)/gi, "LONGTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
  sql = sql.replace(/\bVARCHAR\s*\(\s*MAX\s*\)/gi, "LONGTEXT");
  sql = sql.replace(/\bNVARCHAR\s*\(\s*(\d+)\s*\)/gi, "VARCHAR($1) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
  sql = sql.replace(/\bNCHAR\s*\(\s*(\d+)\s*\)/gi, "CHAR($1) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
  sql = sql.replace(/\bNTEXT\b/gi, "LONGTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
  sql = sql.replace(/\bTEXT\b/gi, "LONGTEXT");

  // Tarih/saat tipleri
  sql = sql.replace(/\bDATETIME2\s*(?:\(\s*\d+\s*\))?/gi, "DATETIME(6)");
  sql = sql.replace(/\bSMALLDATETIME\b/gi, "DATETIME");
  sql = sql.replace(/\bDATETIMEOFFSET\s*(?:\(\s*\d+\s*\))?/gi, "DATETIME(6)");

  // Para
  sql = sql.replace(/\bSMALLMONEY\b/gi, "DECIMAL(10,4)");
  sql = sql.replace(/\bMONEY\b/gi, "DECIMAL(19,4)");

  // Bit/uniqueidentifier/varbinary
  sql = sql.replace(/\bBIT\b/gi, "TINYINT(1)");
  sql = sql.replace(/\bUNIQUEIDENTIFIER\b/gi, "CHAR(36)");
  sql = sql.replace(/\bVARBINARY\s*\(\s*MAX\s*\)/gi, "LONGBLOB");
  sql = sql.replace(/\bIMAGE\b/gi, "LONGBLOB");
  sql = sql.replace(/\bSQL_VARIANT\b/gi, "LONGTEXT");
  sql = sql.replace(/\bXML\b/gi, "LONGTEXT");
  sql = sql.replace(/\bREAL\b/gi, "FLOAT");
  // FLOAT(53) → DOUBLE
  sql = sql.replace(/\bFLOAT\s*\(\s*53\s*\)/gi, "DOUBLE");

  return sql;
}

function transformDefaults(sql) {
  // DEFAULT ((0)) → DEFAULT 0
  sql = sql.replace(/DEFAULT\s+\(\(\s*([^()]+)\s*\)\)/gi, "DEFAULT $1");
  sql = sql.replace(/DEFAULT\s+\(\s*(['"][^'"]*['"]|-?\d+(?:\.\d+)?|NULL)\s*\)/gi, "DEFAULT $1");
  // (getdate()) / getdate() → CURRENT_TIMESTAMP
  sql = sql.replace(/\(\s*getdate\(\)\s*\)/gi, "CURRENT_TIMESTAMP");
  sql = sql.replace(/\bgetdate\(\)/gi, "CURRENT_TIMESTAMP");
  sql = sql.replace(/\bsysdatetime\(\)/gi, "CURRENT_TIMESTAMP(6)");
  // N'...' → '...'
  sql = sql.replace(/\bN'/g, "'");
  // ISNULL → IFNULL
  sql = sql.replace(/\bISNULL\s*\(/gi, "IFNULL(");
  return sql;
}

function stripNoise(sql) {
  // MSSQL'e özgü index/constraint hint'lerini kaldır
  sql = sql.replace(/WITH\s*\(\s*[^)]*?\)\s*ON\s+`?PRIMARY`?/gi, "");
  sql = sql.replace(/WITH\s*\(\s*PAD_INDEX[\s\S]*?\)/gi, "");
  sql = sql.replace(/\s+ON\s+`?PRIMARY`?(?:\s*$|\s*\))/gim, "");
  sql = sql.replace(/\s+TEXTIMAGE_ON\s+`?PRIMARY`?/gi, "");
  sql = sql.replace(/\s+WITH\s+(NOCHECK|CHECK)\b/gi, "");
  sql = sql.replace(/\bASC\b(?=\s*[,)])/gi, "ASC"); // bırak
  sql = sql.replace(/\bCOLLATE\s+[A-Za-z0-9_]+/gi, ""); // server collation'ı geçersiz kıl, default'a düşsün
  // IDENTITY(1,1) → AUTO_INCREMENT
  sql = sql.replace(/IDENTITY\s*\(\s*\d+\s*,\s*\d+\s*\)/gi, "AUTO_INCREMENT");
  // NOT FOR REPLICATION → kaldır
  sql = sql.replace(/\s+NOT\s+FOR\s+REPLICATION\b/gi, "");
  return sql;
}

// ── Statement convertörleri ─────────────────────────────────────────────────
function convertCreateTable(raw) {
  let sql = raw;
  sql = transformIdentifiers(sql);
  sql = transformTypes(sql);
  sql = transformDefaults(sql);
  sql = stripNoise(sql);
  // CREATE TABLE `X` → CREATE TABLE IF NOT EXISTS `X`
  sql = sql.replace(/^\s*CREATE\s+TABLE\s+/i, "CREATE TABLE IF NOT EXISTS ");
  // Engine + charset sonek
  sql = sql.replace(/\s*\)\s*$/m, "\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci");
  return sql;
}

function convertCreateIndex(raw) {
  let sql = raw;
  sql = transformIdentifiers(sql);
  sql = stripNoise(sql);
  // CLUSTERED → kaldır (MySQL'de PK zaten clustered)
  sql = sql.replace(/\bCLUSTERED\s+/gi, "");
  sql = sql.replace(/\bNONCLUSTERED\s+/gi, "");
  // INCLUDE (...) → kaldır (MySQL'de yok, covering index için ayrı kolon ekleme gerek)
  sql = sql.replace(/\s+INCLUDE\s*\([^)]*\)/gi, "");
  return sql;
}

function convertAlterTable(raw) {
  let sql = raw;
  sql = transformIdentifiers(sql);
  sql = transformTypes(sql);
  sql = transformDefaults(sql);
  sql = stripNoise(sql);
  // CHECK CONSTRAINT all kaldır (sürüm uyum)
  sql = sql.replace(/^ALTER\s+TABLE\s+`[^`]+`\s+CHECK\s+CONSTRAINT\s+ALL\s*$/im, "");
  return sql.trim();
}

function convertInsert(raw) {
  let sql = raw;
  sql = transformIdentifiers(sql);
  sql = transformDefaults(sql);
  // INSERT `X` → INSERT IGNORE INTO `X` (mevcut PK çakışmalarını geç)
  sql = sql.replace(/^\s*INSERT\s+(?:INTO\s+)?(`[^`]+`)/i, "INSERT IGNORE INTO $1");
  return sql;
}

// ── Stream akış ─────────────────────────────────────────────────────────────
const rl = createInterface({
  input: createReadStream(inputPath, { encoding: "utf8" }),
  crlfDelay: Infinity,
});

let lineNo = 0;
rl.on("line", (line) => {
  lineNo++;
  // T-SQL batch separator GO (kendi başına bir satırda)
  if (/^\s*GO\s*$/i.test(line)) {
    flushStatement();
    return;
  }
  buffer.push(line);
});

rl.on("close", async () => {
  flushStatement();
  schemaOut.write(footer);
  dataOut.write(footer);
  await Promise.all([
    new Promise((r) => schemaOut.end(r)),
    new Promise((r) => dataOut.end(r)),
    new Promise((r) => skippedOut.end(r)),
  ]);
  console.log("Dönüşüm tamam.");
  console.log(`  Satır       : ${lineNo}`);
  console.log(`  CREATE TABLE: ${stats.tables}`);
  console.log(`  CREATE INDEX: ${stats.indexes}`);
  console.log(`  FK / ALTER  : ${stats.fks}`);
  console.log(`  INSERT      : ${stats.inserts}`);
  console.log(`  Atlanan     : ${stats.skipped} (skipped.log'a yazıldı)`);
  console.log(`Çıktı: ${outDir}`);
});
