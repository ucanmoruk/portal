#!/usr/bin/env node
// MSSQL T-SQL Generate Scripts çıktısını MySQL 8 / MariaDB'ye çevirir.
// Stream-based, UTF-16 auto-detect, ~250 MB tek dosyada sorunsuz.
//
// Kullanım:
//   node scripts/mssql-to-mysql-convert.mjs <input.sql> [output-dir]
//
// Çıktı:
//   <out>/01-schema.sql   — CREATE TABLE IF NOT EXISTS + indexes + FK'ler + VIEW'lar
//   <out>/02-data.sql     — INSERT IGNORE INTO ...
//   <out>/skipped.log     — dönüşemeyen statement'lar (TRIGGER, PROCEDURE, vb.)

import { createReadStream, createWriteStream, mkdirSync, existsSync, openSync, readSync, closeSync } from "node:fs";
import { createInterface } from "node:readline";
import path from "node:path";

// ── Encoding tespit ────────────────────────────────────────────────────────
function detectEncoding(file) {
  const fd = openSync(file, "r");
  const buf = Buffer.alloc(4);
  readSync(fd, buf, 0, 4, 0);
  closeSync(fd);
  if (buf[0] === 0xff && buf[1] === 0xfe) return "utf16le";
  if (buf[0] === 0xef && buf[1] === 0xbb && buf[2] === 0xbf) return "utf8";
  return "utf8";
}

const [, , inputArg, outDirArg] = process.argv;
if (!inputArg) {
  console.error("Kullanım: node scripts/mssql-to-mysql-convert.mjs <input.sql> [output-dir]");
  process.exit(1);
}
const inputPath = path.resolve(inputArg);
const outDir = path.resolve(outDirArg || path.join(path.dirname(inputPath), "mysql-out"));
if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });

const schemaOut = createWriteStream(path.join(outDir, "01-schema.sql"), { encoding: "utf8" });
const dataOut = createWriteStream(path.join(outDir, "02-data.sql"), { encoding: "utf8" });
const skippedOut = createWriteStream(path.join(outDir, "skipped.log"), { encoding: "utf8" });

const header = `-- Generated by mssql-to-mysql-convert.mjs
SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;
SET UNIQUE_CHECKS = 0;
SET sql_mode = '';
`;
const footer = `\nSET FOREIGN_KEY_CHECKS = 1;\nSET UNIQUE_CHECKS = 1;\n`;
schemaOut.write(header);
dataOut.write(header);

// ── Tip listesi (bracket'siz hale getirmek için) ──────────────────────────
const MSSQL_TYPES = [
  "bigint", "int", "smallint", "tinyint", "bit",
  "char", "nchar", "varchar", "nvarchar", "text", "ntext",
  "date", "datetime", "datetime2", "smalldatetime", "datetimeoffset", "time",
  "money", "smallmoney", "decimal", "numeric", "float", "real",
  "uniqueidentifier", "varbinary", "binary", "image", "xml", "sql_variant",
  "rowversion", "timestamp",
];

// ── Transforms ─────────────────────────────────────────────────────────────
function unbracketTypes(sql) {
  // [int] → int  (regex'lerin tip yakalayabilmesi için)
  for (const t of MSSQL_TYPES) {
    sql = sql.replace(new RegExp(`\\[${t}\\]`, "gi"), t);
  }
  return sql;
}

function transformTypes(sql) {
  sql = sql.replace(/\bNVARCHAR\s*\(\s*MAX\s*\)/gi, "LONGTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
  sql = sql.replace(/\bVARCHAR\s*\(\s*MAX\s*\)/gi, "LONGTEXT");
  sql = sql.replace(/\bNVARCHAR\s*\(\s*(\d+)\s*\)/gi, "VARCHAR($1) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
  sql = sql.replace(/\bNCHAR\s*\(\s*(\d+)\s*\)/gi, "CHAR($1) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
  sql = sql.replace(/\bNTEXT\b/gi, "LONGTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
  sql = sql.replace(/\bDATETIME2\s*(?:\(\s*\d+\s*\))?/gi, "DATETIME(6)");
  sql = sql.replace(/\bSMALLDATETIME\b/gi, "DATETIME");
  sql = sql.replace(/\bDATETIMEOFFSET\s*(?:\(\s*\d+\s*\))?/gi, "DATETIME(6)");
  sql = sql.replace(/\bSMALLMONEY\b/gi, "DECIMAL(10,4)");
  sql = sql.replace(/\bMONEY\b/gi, "DECIMAL(19,4)");
  sql = sql.replace(/\bBIT\b/gi, "TINYINT(1)");
  sql = sql.replace(/\bUNIQUEIDENTIFIER\b/gi, "CHAR(36)");
  sql = sql.replace(/\bVARBINARY\s*\(\s*MAX\s*\)/gi, "LONGBLOB");
  sql = sql.replace(/\bIMAGE\b/gi, "LONGBLOB");
  sql = sql.replace(/\bSQL_VARIANT\b/gi, "LONGTEXT");
  sql = sql.replace(/\bXML\b/gi, "LONGTEXT");
  sql = sql.replace(/\bFLOAT\s*\(\s*53\s*\)/gi, "DOUBLE");
  sql = sql.replace(/\bROWVERSION\b/gi, "BIGINT");
  // bare TEXT → LONGTEXT (loose)
  sql = sql.replace(/(?<!LONG)\bTEXT\b/gi, "LONGTEXT");
  return sql;
}

function transformIdentifiers(sql) {
  // [schema].[X] → `X`  (schema bilgisini at)
  sql = sql.replace(/\[[A-Za-z_][\w]*\]\.\[([^\]]+)\]/g, "`$1`");
  // [X] → `X`
  sql = sql.replace(/\[([^\]]+)\]/g, "`$1`");
  // schema.X (bare prefix) → X  (dbo., cosmoroot. vb.)
  sql = sql.replace(/\b(dbo|cosmoroot)\.(`?[A-Za-z_][\w]*`?)/gi, "$2");
  return sql;
}

function transformDefaults(sql) {
  // DEFAULT ((0)) → DEFAULT 0
  sql = sql.replace(/DEFAULT\s+\(\(\s*(-?\d+(?:\.\d+)?|NULL)\s*\)\)/gi, "DEFAULT $1");
  sql = sql.replace(/DEFAULT\s+\(\s*(-?\d+(?:\.\d+)?|NULL)\s*\)/gi, "DEFAULT $1");
  // DEFAULT ((''))  →  DEFAULT ''
  sql = sql.replace(/DEFAULT\s+\(\(\s*(['"][^'"]*['"])\s*\)\)/gi, "DEFAULT $1");
  sql = sql.replace(/DEFAULT\s+\(\s*(['"][^'"]*['"])\s*\)/gi, "DEFAULT $1");
  sql = sql.replace(/\(\s*getdate\(\)\s*\)/gi, "CURRENT_TIMESTAMP");
  sql = sql.replace(/\bgetdate\(\)/gi, "CURRENT_TIMESTAMP");
  sql = sql.replace(/\bsysdatetime\(\)/gi, "CURRENT_TIMESTAMP(6)");
  sql = sql.replace(/\bnewid\(\)/gi, "UUID()");
  sql = sql.replace(/\bN'/g, "'");
  sql = sql.replace(/\bISNULL\s*\(/gi, "IFNULL(");
  return sql;
}

function stripMssqlNoise(sql) {
  // WITH (PAD_INDEX = OFF, ...) ON [PRIMARY] gibi index hint bloklarını kaldır
  sql = sql.replace(/WITH\s*\(\s*[^)]*?\)\s*(?:ON\s+(`PRIMARY`|\[PRIMARY\]))?/gi, "");
  sql = sql.replace(/\bON\s+(`PRIMARY`|\[PRIMARY\])/gi, "");
  sql = sql.replace(/\bTEXTIMAGE_ON\s+(`PRIMARY`|\[PRIMARY\])/gi, "");
  sql = sql.replace(/\bWITH\s+(NOCHECK|CHECK)\b/gi, "");
  sql = sql.replace(/\bCLUSTERED\b/gi, "");
  sql = sql.replace(/\bNONCLUSTERED\b/gi, "");
  sql = sql.replace(/\s+NOT\s+FOR\s+REPLICATION\b/gi, "");
  // COLLATE Turkish_CI_AS gibi server collation'larını sil (MySQL default'a düş)
  sql = sql.replace(/\bCOLLATE\s+[A-Za-z0-9_]+/gi, "");
  // IDENTITY(1,1) → AUTO_INCREMENT
  sql = sql.replace(/IDENTITY\s*\(\s*\d+\s*,\s*\d+\s*\)/gi, "AUTO_INCREMENT");
  // ASC/DESC in column list: MySQL kabul eder ama PRIMARY KEY'de ASC gereksiz — bırakıyoruz
  return sql;
}

function cleanupWhitespace(sql) {
  sql = sql.replace(/[ \t]+\n/g, "\n");
  sql = sql.replace(/\n{3,}/g, "\n\n");
  sql = sql.replace(/[ \t]{2,}/g, " ");
  return sql.trim();
}

// CREATE TABLE'ın sonuna ENGINE/CHARSET clause'u ekle.
// MSSQL output yapısı:
//   CREATE TABLE `X`(
//     ... columns ...
//    CONSTRAINT `PK_X` PRIMARY KEY ( `ID` ASC )
//   )
// Son `)`'den önce hiçbir ENGINE yok — son `)`'yi `) ENGINE=...` yap.
function appendEngineClause(sql) {
  // Son ) konumunu bul
  const lastClose = sql.lastIndexOf(")");
  if (lastClose === -1) return sql;
  const before = sql.slice(0, lastClose);
  const after = sql.slice(lastClose + 1);
  return `${before}) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci${after}`;
}

// ── Statement convertörleri ────────────────────────────────────────────────
function convertCreateTable(raw) {
  let sql = raw;
  sql = unbracketTypes(sql);
  sql = transformTypes(sql);
  sql = stripMssqlNoise(sql);
  sql = transformIdentifiers(sql);
  sql = transformDefaults(sql);
  sql = sql.replace(/^\s*CREATE\s+TABLE\s+/i, "CREATE TABLE IF NOT EXISTS ");
  sql = appendEngineClause(sql);
  sql = cleanupWhitespace(sql);
  return sql;
}

function convertCreateIndex(raw) {
  let sql = raw;
  sql = unbracketTypes(sql);
  sql = transformIdentifiers(sql);
  sql = stripMssqlNoise(sql);
  sql = sql.replace(/\s+INCLUDE\s*\([^)]*\)/gi, "");
  return cleanupWhitespace(sql);
}

function convertAlterTable(raw) {
  let sql = raw;
  sql = unbracketTypes(sql);
  sql = transformTypes(sql);
  sql = stripMssqlNoise(sql);
  sql = transformIdentifiers(sql);
  sql = transformDefaults(sql);
  // ALTER TABLE `X` CHECK CONSTRAINT ALL → işe yaramaz, sil
  if (/^ALTER\s+TABLE\s+`[^`]+`\s+CHECK\s+CONSTRAINT\s+ALL/i.test(sql)) return "";
  return cleanupWhitespace(sql);
}

function convertInsert(raw) {
  let sql = raw;
  sql = unbracketTypes(sql);
  sql = transformIdentifiers(sql);
  // INSERT `X` ile başlayan her satırı INSERT IGNORE INTO `X` yap (multi-INSERT batch'leri için)
  sql = sql.replace(/^\s*INSERT\s+(?:INTO\s+)?(`[^`]+`)/gim, "INSERT IGNORE INTO $1");
  sql = sql.replace(/\bN'/g, "'");
  // Her satır ; ile bitsin (MSSQL multi-INSERT GO bloğunda satırlar ;'siz gelir)
  const lines = sql.split("\n").map((l) => {
    const t = l.trimEnd();
    if (t.startsWith("INSERT") && !t.endsWith(";")) return t + ";";
    return t;
  });
  return lines.join("\n").trim();
}

function convertCreateView(raw) {
  let sql = raw;
  sql = unbracketTypes(sql);
  sql = transformTypes(sql);
  sql = transformIdentifiers(sql);
  sql = transformDefaults(sql);
  // MSSQL'e özgü görüş eklerini at
  sql = sql.replace(/\s+WITH\s+(SCHEMABINDING|VIEW_METADATA|ENCRYPTION)\b/gi, "");
  // [Alias With Space] zaten `Alias With Space` oldu — MySQL kabul eder
  return cleanupWhitespace(sql);
}

// ── Buffer ─────────────────────────────────────────────────────────────────
let buffer = [];
let stats = { tables: 0, indexes: 0, fks: 0, inserts: 0, views: 0, skipped: 0 };

// Buffer'ı statement'lara böl — leading SET / yorum bloklarını ayır.
function splitLeadingNoise(raw) {
  const lines = raw.split("\n");
  const skip = [];
  while (lines.length) {
    const ln = lines[0].trim();
    if (
      ln === "" ||
      /^\/\*[\s\S]*\*\/$/.test(ln) ||
      /^\/\*+/.test(ln) ||
      /\*+\//.test(ln) ||
      /^--/.test(ln) ||
      /^SET\s+(ANSI_NULLS|QUOTED_IDENTIFIER|ANSI_PADDING|NOCOUNT|XACT_ABORT|ARITHABORT|CONCAT_NULL_YIELDS_NULL|ANSI_WARNINGS|NUMERIC_ROUNDABORT)\b/i.test(ln)
    ) {
      skip.push(lines.shift());
    } else {
      break;
    }
  }
  return { skipped: skip.join("\n"), rest: lines.join("\n") };
}

function flushStatement() {
  if (!buffer.length) return;
  const joined = buffer.join("\n");
  buffer = [];
  const { rest } = splitLeadingNoise(joined);
  const raw = rest.trim();
  if (!raw) return;

  // DB-yönetim, kullanıcı, schema, fulltext, statistics → skip
  if (
    /^(CREATE|ALTER|DROP)\s+DATABASE\b/i.test(raw) ||
    /^(CREATE|ALTER|DROP)\s+(USER|LOGIN|SCHEMA|ROLE|STATISTICS|FULLTEXT\s+CATALOG|FULLTEXT\s+INDEX)\b/i.test(raw) ||
    /^(GRANT|DENY|REVOKE)\b/i.test(raw) ||
    /^(ALTER\s+AUTHORIZATION|ALTER\s+ROLE)\b/i.test(raw) ||
    /^EXEC(UTE)?\b/i.test(raw) ||
    /^IF\s*\(\s*1\s*=\s*FULLTEXTSERVICEPROPERTY/i.test(raw) ||
    /^IF\s+NOT\s+EXISTS\s*\(\s*SELECT/i.test(raw) ||
    /^PRINT\s+/i.test(raw) ||
    /^SET\s+IDENTITY_INSERT/i.test(raw)
  ) {
    return;
  }

  const upper = raw.toUpperCase();
  let converted, target;

  if (/^CREATE\s+TABLE\b/i.test(upper)) {
    converted = convertCreateTable(raw);
    target = schemaOut;
    stats.tables++;
  } else if (/^CREATE\s+(UNIQUE\s+)?(CLUSTERED\s+|NONCLUSTERED\s+)?INDEX\b/i.test(upper)) {
    converted = convertCreateIndex(raw);
    target = schemaOut;
    stats.indexes++;
  } else if (/^ALTER\s+TABLE\b/i.test(upper)) {
    converted = convertAlterTable(raw);
    if (!converted) return;
    target = schemaOut;
    if (/FOREIGN\s+KEY/i.test(upper)) stats.fks++;
  } else if (/^CREATE\s+VIEW\b/i.test(upper)) {
    converted = convertCreateView(raw);
    target = schemaOut;
    stats.views++;
  } else if (/^INSERT\b/i.test(upper)) {
    converted = convertInsert(raw);
    target = dataOut;
    stats.inserts++;
  } else if (/^(CREATE\s+(TRIGGER|PROCEDURE|FUNCTION)|EXEC\b)/i.test(upper)) {
    skippedOut.write(`-- SKIPPED (MSSQL T-SQL):\n${raw}\nGO\n\n`);
    stats.skipped++;
    return;
  } else {
    skippedOut.write(`-- UNRECOGNIZED:\n${raw}\nGO\n\n`);
    stats.skipped++;
    return;
  }

  if (converted) target.write(converted + ";\n\n");
}

// ── Stream ─────────────────────────────────────────────────────────────────
const inputEncoding = detectEncoding(inputPath);
console.log(`Encoding tespit: ${inputEncoding}`);
const rl = createInterface({
  input: createReadStream(inputPath, { encoding: inputEncoding }),
  crlfDelay: Infinity,
});

let lineNo = 0;
let bomStripped = false;
rl.on("line", (line) => {
  lineNo++;
  if (!bomStripped) {
    bomStripped = true;
    if (line.charCodeAt(0) === 0xfeff) line = line.slice(1);
  }
  if (/^\s*GO\s*$/i.test(line)) {
    flushStatement();
    return;
  }
  buffer.push(line);
});

rl.on("close", async () => {
  flushStatement();
  schemaOut.write(footer);
  dataOut.write(footer);
  await Promise.all([
    new Promise((r) => schemaOut.end(r)),
    new Promise((r) => dataOut.end(r)),
    new Promise((r) => skippedOut.end(r)),
  ]);
  console.log("Dönüşüm tamam.");
  console.log(`  Satır       : ${lineNo}`);
  console.log(`  CREATE TABLE: ${stats.tables}`);
  console.log(`  CREATE VIEW : ${stats.views}`);
  console.log(`  CREATE INDEX: ${stats.indexes}`);
  console.log(`  FK / ALTER  : ${stats.fks}`);
  console.log(`  INSERT      : ${stats.inserts}`);
  console.log(`  Atlanan     : ${stats.skipped} (skipped.log'a yazıldı)`);
  console.log(`Çıktı: ${outDir}`);
});
